/**
 * Materialize public/spa.html into lib/spa-html.ts so the `/` Route Handler
 * can return the shell from the serverless bundle (no runtime fs.readFile of
 * public/ — those files are not in the Vercel function file trace).
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const spaPath = path.join(root, "public", "spa.html");
const indexPath = path.join(root, "public", "index.html");
const outPath = path.join(root, "lib", "spa-html.ts");

const html = await readFile(spaPath, "utf8");
if (!html.includes("<!DOCTYPE html>") || !html.includes("/static/app.js")) {
  console.error("sync_spa_html: public/spa.html looks invalid");
  process.exit(1);
}

// Keep public/index.html identical so a mis-detected static deploy still has `/`.
await writeFile(indexPath, html);

await mkdir(path.dirname(outPath), { recursive: true });
const body = `/* Auto-generated by scripts/sync_spa_html.mjs — do not edit. */\nexport const SPA_HTML = ${JSON.stringify(html)};\n`;
await writeFile(outPath, body);
console.log(
  `sync_spa_html: wrote ${path.relative(root, outPath)} + public/index.html (${html.length} chars)`,
);
